namespace Atividade_POO
{
    public class Calculadora
    {
        public int Somar(int a, int b)
        {
            return a+b;
        }

        public int Subtrair(int a, int b)
        {
            return a - b;
        }

        public double Multiplicar(double a, double b)
        {
            return a * b;
        }

        public static decimal Dividir(decimal a, decimal b)
        {
            return a / b;
        }
    }
}